/**
 * MarkdownExporter
 * Converts a ResearchPilot report JSON into a publication-grade GitHub Flavored Markdown document.
 */

function formatReportAsMarkdown(report, query = "") {
  if (!report) return "# Research Report\n\nNo report content available.";

  const title = report.title || `Research Report: ${query}`;
  const now = new Date().toISOString();

  const lines = [];

  // Title & Metadata
  lines.push(`# ${title}`);
  lines.push("");
  lines.push(`> **Generated by ResearchPilot Multi-Agent Engine**  `);
  if (query) {
    lines.push(`> **Research Query:** *${query}*  `);
  }
  lines.push(`> **Timestamp:** ${now}  `);
  lines.push("");
  lines.push("---");
  lines.push("");

  // Executive Summary
  if (report.executive_summary) {
    lines.push("## Executive Summary");
    lines.push("");
    lines.push(report.executive_summary);
    lines.push("");
  }

  // Industry Overview
  if (report.industry_overview) {
    lines.push("## Industry Overview & Context");
    lines.push("");
    lines.push(report.industry_overview);
    lines.push("");
  }

  // Key Findings
  if (Array.isArray(report.key_findings) && report.key_findings.length > 0) {
    lines.push("## Key Research Discoveries");
    lines.push("");
    report.key_findings.forEach((finding, idx) => {
      lines.push(`${idx + 1}. ${finding}`);
    });
    lines.push("");
  }

  // Fact-Checked Claims Audit
  if (Array.isArray(report.claims) && report.claims.length > 0) {
    lines.push("## Fact-Checked Claims Audit");
    lines.push("");
    lines.push("| Assertion | Verification Status | Confidence | Evidence Quote | Citation Source |");
    lines.push("| :--- | :---: | :---: | :--- | :--- |");
    report.claims.forEach(c => {
      const statusBadge = (c.verification_status || "UNKNOWN").toUpperCase();
      const conf = c.confidence_score !== undefined ? `${Math.round(c.confidence_score * 100)}%` : "N/A";
      const quote = (c.evidence_quote || "N/A").replace(/\|/g, "\\|").replace(/\n/g, " ");
      const source = (c.citation_source || "N/A").replace(/\|/g, "\\|");
      const text = (c.claim_text || "").replace(/\|/g, "\\|").replace(/\n/g, " ");
      lines.push(`| ${text} | **${statusBadge}** | ${conf} | *"${quote}"* | ${source} |`);
    });
    lines.push("");
  }

  // Contradictory Findings
  if (Array.isArray(report.contradictory_findings) && report.contradictory_findings.length > 0) {
    lines.push("## Contradictory Findings & Discrepancies");
    lines.push("");
    lines.push("> [!WARNING]");
    lines.push("> The following assertions or measurements exhibit contradictory evidence across sources:");
    lines.push("");
    report.contradictory_findings.forEach(cf => {
      lines.push(`- ${cf}`);
    });
    lines.push("");
  }

  // Opportunities
  if (Array.isArray(report.opportunities) && report.opportunities.length > 0) {
    lines.push("## Strategic Opportunities");
    lines.push("");
    report.opportunities.forEach(opp => {
      lines.push(`- ${opp}`);
    });
    lines.push("");
  }

  // Risks & Challenges
  if (Array.isArray(report.risks_and_challenges) && report.risks_and_challenges.length > 0) {
    lines.push("## Risks, Vulnerabilities & Challenges");
    lines.push("");
    report.risks_and_challenges.forEach(risk => {
      lines.push(`- ${risk}`);
    });
    lines.push("");
  }

  // Future Outlook
  if (report.future_outlook) {
    lines.push("## 3-to-5 Year Strategic Outlook");
    lines.push("");
    lines.push(report.future_outlook);
    lines.push("");
  }

  // References & Provenance
  if (Array.isArray(report.references) && report.references.length > 0) {
    lines.push("## Verified Sources & Provenance");
    lines.push("");
    report.references.forEach((ref, idx) => {
      const label = ref.citation_label || `[${idx + 1}]`;
      const title = ref.title || "Source";
      if (ref.source_type === "web" && ref.url) {
        lines.push(`- ${label} **${title}** — [${ref.url}](${ref.url})`);
      } else {
        const pageInfo = ref.page_number ? ` (Page ${ref.page_number})` : "";
        lines.push(`- ${label} **${title}**${pageInfo}`);
      }
      if (ref.snippet) {
        lines.push(`  > *"${ref.snippet.replace(/\n/g, ' ')}"*`);
      }
    });
    lines.push("");
  }

  return lines.join("\n");
}

module.exports = { formatReportAsMarkdown };

