import uuid
from typing import List, Dict, Any, Optional
from sqlalchemy.ext.asyncio import AsyncSession
from app.services.retrieval_service import RetrievalService

class DocumentResearchAgent:
    """Specialized agent performing semantic RAG retrieval across uploaded PDFs with multi-doc and user scoping."""

    def __init__(self, db: AsyncSession, retrieval_service: Optional[RetrievalService] = None):
        self.db = db
        self.retrieval_service = retrieval_service or RetrievalService(db)

    async def research(
        self,
        sub_questions: List[Dict[str, Any]],
        document_ids: Optional[List[str]] = None,
        user_id: Optional[uuid.UUID] = None,
        top_k_per_question: int = 4
    ) -> List[Dict[str, Any]]:
        evidence_items = []
        seen_chunks = set()

        # Parse target document UUIDs if provided
        target_doc_uuids: List[uuid.UUID] = []
        if document_ids:
            for d in document_ids:
                try:
                    target_doc_uuids.append(uuid.UUID(str(d)))
                except (ValueError, TypeError):
                    pass

        for sq in sub_questions:
            source_type = sq.get("source_type", "both")
            if source_type not in ["document", "both"]:
                continue

            # Prefer optimized search_query if generated by Planner, else fallback to question
            q_text = sq.get("search_query") or sq.get("question", "")
            chunks = await self.retrieval_service.search(
                query=q_text,
                document_ids=target_doc_uuids if target_doc_uuids else None,
                top_k=top_k_per_question,
                threshold=0.2, # Minimum relevance filter
                user_id=user_id,
            )

            # Resilient fallback: if optimized search_query retrieved no chunks, fallback to original question
            if not chunks and sq.get("question") and sq.get("question") != q_text:
                chunks = await self.retrieval_service.search(
                    query=sq.get("question"),
                    document_ids=target_doc_uuids if target_doc_uuids else None,
                    top_k=top_k_per_question,
                    threshold=0.2,
                    user_id=user_id,
                )

            for c in chunks:
                chunk_id = c["chunk_id"]
                if chunk_id in seen_chunks:
                    continue
                seen_chunks.add(chunk_id)

                evidence_items.append({
                    "id": str(uuid.uuid4()),
                    "source_type": "document",
                    "title": f"Document: {c['filename']} (Page {c['page_number']})",
                    "content": c["content"],
                    "url": None,
                    "document_id": c["document_id"],
                    "page_number": c["page_number"],
                    "published_date": None,
                    "relevance_score": c["similarity_score"],
                    "sub_question_id": sq.get("id"),
                })

        return evidence_items

